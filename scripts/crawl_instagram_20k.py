def run_multilingual_20k_generation(
    total_count: int = 20000,
    output_jsonl: str = "data/raw/instagram_20k_dataset.jsonl",
    output_json: str = "data/raw/instagram_20k_dataset.json",
    sync_signals: bool = True,
    save_to_db: bool = False
):
    print("=" * 85)
    print(f"BHARAT-SHIELD: MULTILINGUAL & SEMANTICALLY DIVERSE INSTAGRAM DATASET GENERATOR")
    print(f"Target: {total_count:,} Records | 11 Indian Languages | Multimodal OCR/ASR Engine")
    print("=" * 85)

    t0 = time.time()
    start_time = datetime.now(timezone.utc)

    jsonl_path = PROJECT_ROOT / output_jsonl
    json_path = PROJECT_ROOT / output_json
    jsonl_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"\n[1/4] Generating & Writing {total_count:,} multilingual records to JSONL ({jsonl_path.name})...")
    
    all_records: List[Dict[str, Any]] = []
    lang_counter: Dict[str, int] = {}
    
    with open(jsonl_path, "w", encoding="utf-8") as f_jsonl:
        for idx in range(1, total_count + 1):
            rec = generate_multilingual_record(idx, start_time)
            f_jsonl.write(json.dumps(rec, ensure_ascii=False) + "\n")
            all_records.append(rec)
            
            l_code = rec["language_analysis"]["language"]
            lang_counter[l_code] = lang_counter.get(l_code, 0) + 1
            
            if idx % 5000 == 0 or idx == total_count:
                elapsed = time.time() - t0
                rate = idx / (elapsed if elapsed > 0 else 0.001)
                print(f"   ✓ Generated {idx:,}/{total_count:,} records ({rate:,.0f} records/sec)")

    print(f"\n[2/4] Writing full JSON array (20k objects) to {json_path.name}...")
    with open(json_path, "w", encoding="utf-8") as f_json:
        json.dump(all_records, f_json, ensure_ascii=False, indent=2)

    # Sync primary signals file for UI / API feeds
    if sync_signals:
        signals_json = PROJECT_ROOT / "data" / "raw" / "instagram_signals.json"
        signals_jsonl = PROJECT_ROOT / "data" / "raw" / "instagram_signals.jsonl"
        print(f"\n[3/4] Syncing primary signals feed ({signals_json.name})...")
        
        top_signals = sorted(all_records, key=lambda x: (x["threat_score"], x["likes"]), reverse=True)[:500]
        with open(signals_json, "w", encoding="utf-8") as f_sig:
            json.dump(top_signals, f_sig, ensure_ascii=False, indent=2)
            
        with open(signals_jsonl, "w", encoding="utf-8") as f_sigl:
            for r in top_signals:
                f_sigl.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"   ✓ Synced {len(top_signals)} priority signals to {signals_json.name}")

    if save_to_db:
        print("\n[4/4] Ingesting sample records into PostgreSQL database...")
        try:
            from database.db import is_db_available, insert_signal
            if is_db_available():
                sample_to_insert = all_records[:500]
                for r in sample_to_insert:
                    insert_signal(r)
                print(f"   ✓ Persisted {len(sample_to_insert)} high-priority records into PostgreSQL!")
            else:
                print("   ℹ PostgreSQL not reachable. Skipping DB ingestion.")
        except Exception as e:
            print(f"   ⚠ DB Ingestion warning: {e}")
    else:
        print("\n[4/4] DB Ingestion skipped (Run with '--save-db' to persist into PostgreSQL).")

    total_time = time.time() - t0
    jsonl_size_mb = jsonl_path.stat().st_size / (1024 * 1024)
    json_size_mb = json_path.stat().st_size / (1024 * 1024)

    print("\n" + "=" * 85)
    print("SUCCESS: 20,000 MULTILINGUAL INSTAGRAM INTELLIGENCE RECORDS GENERATED!")
    print(f"• JSONL Output: {jsonl_path} ({jsonl_size_mb:.2f} MB)")
    print(f"• JSON Array Output: {json_path} ({json_size_mb:.2f} MB)")
    print(f"• Total Records: {len(all_records):,}")
    print(f"• Generation Speed: {total_time:.2f}s ({len(all_records)/total_time:,.0f} records/sec)")
    print("\nLanguage Breakdown:")
    for l_code, cnt in sorted(lang_counter.items(), key=lambda x: x[1], reverse=True):
        lang_name = LANG_CONFIGS.get(l_code, {}).get("name", l_code)
        pct = (cnt / total_count) * 100
        print(f"  - {lang_name} ({l_code}): {cnt:,} records ({pct:.1f}%)")
    print("=" * 85)

